//! `palette-host serve` end to end, in temporary directories only: no
//! profile, data or depot under /etc, /opt or /var is ever touched.

use serde_json::{json, Value};
use std::collections::HashMap;
use std::fs;
use std::io::Write;
use std::os::unix::fs::{symlink, PermissionsExt};
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};

const HOST: &str = "runtime/host/target/release/palette-host";


fn write(path: &Path, contents: &str, mode: u32) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, contents).unwrap();
    fs::set_permissions(path, fs::Permissions::from_mode(mode)).unwrap();
}

fn checkout() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").canonicalize().unwrap()
}

struct Fixture {
    root: PathBuf,
}

impl Drop for Fixture {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

impl Fixture {
    fn new() -> Fixture {
        static COUNT: AtomicUsize = AtomicUsize::new(0);
        let tmp = fs::canonicalize(std::env::temp_dir()).unwrap();
        let root = tmp.join(format!("palette-serve-it-{}-{} with space", std::process::id(), COUNT.fetch_add(1, Ordering::Relaxed)));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(root.join("home")).unwrap();
        Fixture { root }
    }

    fn profile(&self) -> PathBuf {
        self.root.join("config/profile.json")
    }

    fn repo(&self) -> PathBuf {
        self.root.join("repo")
    }

    fn bin(&self) -> PathBuf {
        self.root.join("bin")
    }

    fn record(&self) -> PathBuf {
        self.root.join("record.log")
    }

    /// A stub that logs its argv, then its environment, to the record. The
    /// path is written into the stub, since serve passes no ambient variable.
    fn recorder(&self, name: &str) {
        self.recorder_at(&self.bin().join(name));
    }

    fn recorder_at(&self, path: &Path) {
        let log = self.record().to_string_lossy().replace('\'', "'\\''");
        let script = format!("#!/bin/sh\n{{ printf '%s\\n' \"$0\" \"$@\"; echo ---; env; echo ===; }} >> '{log}'\n");
        write(path, &script, 0o755);
    }

    /// A repo whose sources are this checkout's and whose release host is
    /// the binary under test, so the real adapter can start without a
    /// release build.
    fn link_checkout(&self) {
        let repo = self.repo();
        fs::create_dir_all(repo.join("runtime/host/target/release")).unwrap();
        symlink(checkout().join("Project.toml"), repo.join("Project.toml")).unwrap();
        // The manifest is generated by instantiate; listing tools never reads it.
        match checkout().join("Manifest.toml") {
            m if m.is_file() => symlink(m, repo.join("Manifest.toml")).unwrap(),
            _ => fs::write(repo.join("Manifest.toml"), "").unwrap(),
        }
        symlink(checkout().join("runtime/security"), repo.join("runtime/security")).unwrap();
        symlink(env!("CARGO_BIN_EXE_palette-host"), repo.join(HOST)).unwrap();
    }

    fn command(&self, args: &[&str], path: &str) -> Command {
        let mut c = Command::new(env!("CARGO_BIN_EXE_palette-host"));
        c.arg("serve")
            .args(args)
            .env_clear()
            .env("HOME", self.root.join("home"))
            .env("PATH", path)
            .current_dir(&self.root)
            .stdin(Stdio::null());
        c
    }

    fn run(&self, args: &[&str]) -> Output {
        self.command(args, "/usr/local/bin:/usr/bin:/bin").output().unwrap()
    }

    fn ok(&self, args: &[&str]) -> String {
        let out = self.run(args);
        assert!(out.status.success(), "serve {args:?} failed: {}", String::from_utf8_lossy(&out.stderr));
        String::from_utf8(out.stdout).unwrap()
    }

    fn err(&self, args: &[&str]) -> String {
        let out = self.run(args);
        assert_eq!(out.status.code(), Some(2), "serve {args:?} should fail");
        String::from_utf8(out.stderr).unwrap()
    }

    fn init_args(&self) -> Vec<String> {
        let at = |s: &str| self.root.join(s).to_string_lossy().into_owned();
        [
            "init", "--profile", &at("config/profile.json"), "--repo", &at("repo"), "--data", &at("data"),
            "--depot", &at("depot"), "--ceiling", &at("config/ceiling.json"), "--runtime-root", &at("capabilities"),
        ]
        .map(String::from)
        .to_vec()
    }

    fn init(&self) -> Value {
        serde_json::from_str(&self.ok(&args(&self.init_args()))).unwrap()
    }

    /// Each recorded call: its argv, then its environment.
    fn calls(&self) -> Vec<(Vec<String>, HashMap<String, String>)> {
        let log = fs::read_to_string(self.record()).unwrap_or_default();
        log.split("===\n").filter(|c| !c.is_empty()).map(|call| {
            let (argv, env) = call.split_once("---\n").unwrap();
            let env = env.lines().filter_map(|l| l.split_once('=')).map(|(k, v)| (k.into(), v.into())).collect();
            (argv.lines().map(str::to_string).collect(), env)
        }).collect()
    }
}

fn args(v: &[String]) -> Vec<&str> {
    v.iter().map(String::as_str).collect()
}

#[test]
fn init_inspect_and_client_report_the_profile() {
    let f = Fixture::new();
    let s = |p: PathBuf| p.to_string_lossy().into_owned();
    let report = f.init();
    assert_eq!(report, json!({"profile": s(f.profile()), "repo": s(f.repo()), "workspace": s(f.root.join("data/workspace")),
                              "state": s(f.root.join("data/state")), "compute": "server", "edge_required": false}));
    assert_eq!(fs::metadata(f.profile()).unwrap().permissions().mode() & 0o777, 0o600);
    assert_eq!(fs::metadata(f.root.join("config")).unwrap().permissions().mode() & 0o777, 0o700);
    let written: Value = serde_json::from_str(&fs::read_to_string(f.profile()).unwrap()).unwrap();
    assert_eq!(written["format"], 1);
    assert_eq!(written["read_roots"], json!([]));
    let inspect: Value = serde_json::from_str(&f.ok(&["inspect", "--profile", &s(f.profile())])).unwrap();
    assert_eq!(inspect, report);

    // An existing profile is refused and left as it was.
    fs::write(f.profile(), fs::read_to_string(f.profile()).unwrap().replace("\"read_roots\": []", "\"read_roots\": [\"/srv\"]")).unwrap();
    let before = fs::read_to_string(f.profile()).unwrap();
    assert!(f.err(&args(&f.init_args())).contains("exists"));
    assert_eq!(fs::read_to_string(f.profile()).unwrap(), before);

    let client: Value = serde_json::from_str(&f.ok(&["client", "--profile", &s(f.profile()), "--ssh-target", "palette@server"])).unwrap();
    let entry = &client["mcpServers"]["palette"];
    assert_eq!(entry["command"], "ssh");
    let a = entry["args"].as_array().unwrap();
    assert_eq!(a[..3], [json!("-T"), json!("--"), json!("palette@server")]);
    assert_eq!(a.len(), 4);
    // The fixture root holds a space, so both paths are quoted for the remote shell.
    assert_eq!(a[3].as_str().unwrap(), format!("'{}/{HOST}' serve launch --profile '{}'", s(f.repo()), s(f.profile())));
    for bad in ["-oProxyCommand=x", "a b"] {
        assert!(f.err(&["client", "--profile", &s(f.profile()), "--ssh-target", bad]).contains("valid --ssh-target"));
    }
    assert!(f.err(&["client", "--profile", &s(f.profile())]).contains("valid --ssh-target"));
    assert!(f.err(&["inspect"]).contains("--profile is required"));
    assert!(f.err(&["inspect", "--profile", &s(f.profile()), "--bogus", "1"]).contains("unknown option --bogus"));
    assert!(f.err(&["frobnicate", "--profile", &s(f.profile())]).contains("usage"));
}

#[test]
fn init_removes_a_profile_it_cannot_use() {
    let f = Fixture::new();
    let mut a = f.init_args();
    let data = f.root.join("data").to_string_lossy().into_owned();
    let repo_at = a.iter().position(|x| x == "--repo").unwrap() + 1;
    a[repo_at] = format!("{data}/hidden");
    assert!(f.err(&args(&a)).contains("overlaps protected repo"));
    assert!(!f.profile().exists());
    a[repo_at] = "relative/repo".into();
    assert!(f.err(&args(&a)).contains("repo must be an absolute server path"));
    assert!(!f.profile().exists());
}

#[test]
fn launch_passes_only_the_profile_environment() {
    let f = Fixture::new();
    f.init();
    f.recorder_at(&f.repo().join(HOST));
    let path = format!("{}:/usr/bin:/bin", f.bin().display());
    let out = f
        .command(&["launch", "--profile", &f.profile().to_string_lossy()], &path)
        .env("OPENAI_API_KEY", "fixture-secret")
        .env("PALETTE_HOST_COMMANDS", "fixture-secret")
        .env("PALETTE_PATCH_ROOTS", r#"{"unsafe":"/"}"#)
        .env("LANG", "C.UTF-8")
        .output()
        .unwrap();
    assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    let calls = f.calls();
    assert_eq!(calls.len(), 1);
    let (argv, env) = &calls[0];
    assert_eq!(argv[1..], ["mcp", "start"]);
    for secret in ["OPENAI_API_KEY", "PALETTE_HOST_COMMANDS", "PALETTE_PATCH_ROOTS"] {
        assert!(!env.contains_key(secret), "{secret} was inherited");
    }
    assert_eq!(env["LANG"], "C.UTF-8");
    assert_eq!(env["PATH"], path);
    assert_eq!(env["PALETTE_PACKAGE_DEPOT"], f.root.join("data/packages").to_string_lossy());
    assert_eq!(env["JULIA_DEPOT_PATH"], f.root.join("depot").to_string_lossy());
    assert_eq!(env["JULIA_PKG_OFFLINE"], "true");
    assert_eq!((env["PALETTE_TURN_TIMEOUT"].as_str(), env["PALETTE_MAX_TURN_TIMEOUT"].as_str()), ("60", "1800"));
}

#[test]
fn launch_serves_the_real_adapter_over_stdio() {
    let f = Fixture::new();
    f.link_checkout();
    write(&f.root.join("config/ceiling.json"), r#"{"host_request": {"allowed_types": ["palette.runtime"]}}"#, 0o600);
    f.init();
    let mut child = f
        .command(&["launch", "--profile", &f.profile().to_string_lossy()], "/usr/local/bin:/usr/bin:/bin")
        .env("OPENAI_API_KEY", "fixture-secret")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap();
    let request = json!({"jsonrpc": "2.0", "id": 1, "method": "tools/list"});
    child.stdin.take().unwrap().write_all(format!("{request}\n").as_bytes()).unwrap();
    let out = child.wait_with_output().unwrap();
    assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    let reply: Value = serde_json::from_slice(&out.stdout).unwrap();
    let mut tools: Vec<&str> = reply["result"]["tools"].as_array().unwrap().iter().map(|t| t["name"].as_str().unwrap()).collect();
    tools.sort();
    assert_eq!(tools, ["palette", "palette_control", "palette_patch", "palette_workspace"]);
}

#[test]
fn prepare_provisions_with_package_networking_on() {
    let f = Fixture::new();
    f.init();
    fs::create_dir_all(f.repo()).unwrap();
    for tool in ["julia", "cargo", "bwrap"] {
        f.recorder(tool);
    }
    f.recorder_at(&f.repo().join(HOST));
    let path = f.bin().to_string_lossy().into_owned();
    let profile = f.profile().to_string_lossy().into_owned();
    let out = f.command(&["prepare", "--profile", &profile], &(path.clone() + ":/usr/bin:/bin")).output().unwrap();
    assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    for dir in ["data", "depot", "capabilities"] {
        assert_eq!(fs::metadata(f.root.join(dir)).unwrap().permissions().mode() & 0o777, 0o700, "{dir}");
    }
    let repo = f.repo().to_string_lossy().into_owned();
    let calls = f.calls();
    let argv: Vec<Vec<String>> = calls.iter().map(|(a, _)| a.clone()).collect();
    let tool = |name: &str| f.bin().join(name).to_string_lossy().into_owned();
    assert_eq!(argv, [
        vec![tool("julia"), "--startup-file=no".into(), format!("--project={repo}"), "-e".into(), "using Pkg; Pkg.instantiate()".into()],
        vec![tool("cargo"), "build".into(), "--release".into(), "--locked".into(), "--manifest-path".into(), format!("{repo}/runtime/host/Cargo.toml")],
        vec![format!("{repo}/{HOST}"), "prepare".into(), "--project-dir".into(), repo.clone()],
    ]);
    for (_, env) in &calls {
        assert_eq!(env["JULIA_PKG_OFFLINE"], "false");
        assert_eq!(env["PWD"].as_str(), repo);
    }

    // A missing prerequisite stops before anything runs.
    fs::remove_file(f.bin().join("bwrap")).unwrap();
    fs::remove_file(f.record()).unwrap();
    let out = f.command(&["prepare", "--profile", &profile], &path).output().unwrap();
    assert_eq!(out.status.code(), Some(2));
    assert!(String::from_utf8_lossy(&out.stderr).contains("Missing server prerequisite: bwrap"));
    assert!(f.calls().is_empty());
}
